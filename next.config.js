import { readFileSync } from 'node:fs';
import path from 'node:path';

/** @type {import('next').NextConfig} */
const isProd = process.env.NODE_ENV === 'production';

const ContentSecurityPolicy = [
  "default-src 'self'",
  // 'unsafe-eval' is only needed by the dev overlay; production stays strict.
  isProd ? "script-src 'self' 'unsafe-inline'" : "script-src 'self' 'unsafe-eval' 'unsafe-inline'",
  "style-src 'self' 'unsafe-inline'",
  "img-src 'self' blob: data: https:",
  "font-src 'self' data:",
  "connect-src 'self' https://wa.me https://api.whatsapp.com https://*.supabase.co https://*.imagekit.io ws: wss:",
  "frame-ancestors 'self'",
  "form-action 'self' https://wa.me https://api.whatsapp.com",
  "base-uri 'self'",
  "object-src 'none'",
  isProd ? 'upgrade-insecure-requests' : '',
]
  .filter(Boolean)
  .join('; ');

/**
 * Every URL the previous version of the site exposed (628 historical URLs,
 * 257 keyword aliases and 7 merged category pages) is 301-redirected to its
 * closest new equivalent. Generated by scripts/build-legacy-redirects.mjs.
 */
const legacyRedirects = (() => {
  try {
    const file = path.join(process.cwd(), 'src/data/legacy-redirects.json');
    return JSON.parse(readFileSync(file, 'utf8'));
  } catch {
    return [];
  }
})();

